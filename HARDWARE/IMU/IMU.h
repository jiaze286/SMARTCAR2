#ifndef __IMU_H
#define __IMU_H

#include "stm32f10x.h"

/* ============================================================
 * MPU-6050 六轴 IMU（GY-521 类模块）
 *
 * 接线（独立 I2C1，和 OLED 的软件 I2C 分开，互不干扰）：
 *   VCC -> 3V3      GND -> GND
 *   SCL -> PB8      SDA -> PB9
 *   INT 没接 -> 只能轮询（MPU6050 内部 1kHz 采样，5ms 读一次总能拿到新值）
 *
 * 【为什么必须重映射】
 *   I2C1 默认在 PB6/PB7，那两脚给了 TIM4 出 PWM。
 *   所以初始化里必须开 AFIO 时钟 + GPIO_PinRemapConfig(GPIO_Remap_I2C1)。
 * ============================================================ */

/* ------------------------------------------------------------
 * 陀螺 Z 轴符号。
 * 模块装反了（背面朝上）会让阻尼变成正反馈 —— 车会自己打转！
 *
 * 验证方法：车静止不动，手动把车【向左转】（俯视逆时针），
 *          看 OLED 上的 dz 应该是【正】的。是负的就改这里。
 * ------------------------------------------------------------ */
/* ============================================================
 * 【总开关】0 = 完全不用陀螺仪：不初始化、不读 I2C。
 *   排故用：先用 0 确认其它功能（电机/循迹/遥测）正常，
 *   再改成 1 把陀螺接进来。
 * ============================================================ */
#define USE_IMU   1   /* 1 = 启用陀螺仪；0 = 完全不用（排故用） */

#define IMU_GYRO_Z_SIGN   (-1.0f)

/* ±2000dps 量程：16.4 LSB = 1 °/s */
#define IMU_GYRO_LSB_PER_DPS   16.4f

/* IMU_Init() 的返回值 */
#define IMU_OK           0u
#define IMU_ERR_I2C      1u   /* I2C 无应答：接线 / 供电 / 重映射问题 */
#define IMU_ERR_WHOAMI   2u   /* WHO_AM_I 不是 0x68：芯片不对 */

uint8_t IMU_Init(void);
uint8_t IMU_WhoAmI(void);              /* 读 0x75：0x68=6050, 0x70=6500 */

/* 扫 I2C 总线：返回第一个有应答的 7 位地址（0 = 一个都没应答）。
   用来判断芯片到底在不在、在哪个地址上。 */
uint8_t IMU_ScanAddr(void);

/* 读一次陀螺。放控制循环里，但要降频（建议 5~10ms 一次，别每圈都读）。 */
void    IMU_Update(void);

float   IMU_GetGyroZDps(void);         /* 减零偏、乘符号后的角速度，°/s */
int16_t IMU_GetGyroZRaw(void);         /* 原始值，调试用 */

/* 静止标定零偏。samples 建议 200（约 1 秒）。返回 1 = 成功。
   标定期间车必须【完全静止】、电机不能转。 */
uint8_t IMU_GyroCalib(uint16_t samples);
float   IMU_GetGyroBiasZ(void);

#endif
