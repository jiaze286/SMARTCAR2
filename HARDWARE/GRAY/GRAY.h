#ifndef __GRAY_H
#define __GRAY_H

#include "stm32f10x.h"

/* ============================================================
 * 亚博 8 路灰度巡线模块驱动
 *
 * 接线（模块 6P -> MCU）：
 *   5V   -> 5V
 *   AD0  -> PA2      通道选择，**AD0 是最低位**
 *   AD1  -> PA3
 *   AD2  -> PA4
 *   OUT  -> PA5      数字量输出（不是模拟量！）
 *   GND  -> GND
 *
 * 读取流程（官方要求）：选通道 -> delay_us(50) -> 读 OUT
 * 8 路扫一遍约 400us
 * ============================================================ */

#define GRAY_CH_NUM   8

/* ------------------------------------------------------------
 * 误差放大倍数。
 * 权重只有 {-5,-4,-2,-1,1,2,4,5}，取平均后是整数除法，误差只有
 * ±1,±2,±4,±5 几个离散值 —— 小误差时 ±1 直接跳到 ±2，太粗，
 * 撑不起高 Kp。放大 10 倍后分辨率变 0.1，修正平滑得多。
 *
 * 【注意】GRAY_GetError() 的返回值也跟着放大 10 倍，
 *         所有跟误差相乘的参数（Kp、Ks、D）都要相应缩小 10 倍。
 * ------------------------------------------------------------ */
#define GRAY_ERR_SCALE   10

/* ------------------------------------------------------------
 * 压线时 OUT 的电平。
 * 【换场地必须重新确认这个值！】
 *   白底黑线 -> 1（模块出厂就是这个，压黑线时输出高）
 *   黑底白线 -> 0
 * 判断依据：把车摆正压在线上，看 OLED 第 2 行中间几位是不是 1。
 *   中间是 1 = 对；中间是 0 = 反了，改这个值。
 *
 *   把车放在赛道上，看 OLED 上 8 路状态里"正对着黑线"的那一路是不是 1。
 *   如果是 0，把下面改成 0。
 * ------------------------------------------------------------ */
#define GRAY_LINE_VALUE   0

void    GRAY_Init(void);

/* 扫一遍 8 路，结果和误差都缓存在模块内部 */
void    GRAY_ReadAll(void);

/* 取第 i 路状态（i = 0~7），1 = 压线 */
uint8_t GRAY_GetChannel(uint8_t i);

/* 加权重心偏差，范围约 -5 ~ +5，0 = 正中
 * 负 = 线偏左（车要左转），正 = 线偏右 */
int16_t GRAY_GetError(void);

/* 1 = 丢线（8 路全没压到） */
uint8_t GRAY_IsLost(void);

/* 1 = 8 路全压线（放错位置了，该锁死电机） */
uint8_t GRAY_IsAllOn(void);

#endif
