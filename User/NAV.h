#ifndef __NAV_H
#define __NAV_H

#include "stm32f10x.h"

/* ============================================================
 * 惯性导航（惯导为主、光电为辅）—— 【地图直接输入】版
 *
 * 和 ins-nav 分支那一版的区别：
 *   那一版要先【手推车建图】跑一圈把路表记下来、再存进片内 Flash；
 *   这一版的路表是【离线生成好、直接编译进来】的（导航地图/nav_map_fw.h），
 *   所以不需要建图、不需要 Flash 读写、不占 RAM。
 *
 * 【怎么跑】
 *   1. 把车摆在发车点，车头对准赛道前进方向
 *      （见 nav_map_fw.h 的 NAV_MAP_START_X_MM / Y_MM / YAW_MDEG）；
 *   2. 上电 -> 陀螺零偏标定（这段时间车必须静止）；
 *   3. 进 MODE_NAV：按编码器里程在路表上取【前瞻点】，
 *      拿惯导估计出来的位姿当车开（纯跟踪）；
 *   4. 光电只在【直道中段】(kind == 2) 用来修陀螺的航向漂移。
 *
 * 【为什么这样能过葫芦圈 / 十字 / 直角弯】
 *   路表里记的就是"该走的路径"。相切点该跟哪条线、十字该不该直行，
 *   全都不用判断 —— 不需要找标志，也没有专门的元素逻辑。
 *
 * 【坐标与角度约定】必须和 nav_map_fw.h 一致：
 *   原点 = 场地左上角，X 向右，Y 向下，yaw 0 度 = +X，顺时针为正。
 *   位置单位 mm；对外航向用 0.1 度（内部累加用 0.001 度，防整除截断）。
 * ============================================================ */

/* ------------------------------------------------------------
 * 【台架必校，第一次上车第一件事】陀螺符号
 *
 *   地图的 yaw 约定：0 度 = +X，yaw 增大 = 车往 +Y 方向拐（地图的 Y 朝下）。
 *   本工程里 IMU_GYRO_Z_SIGN 已定成"向左转时 dz 为正"，所以
 *   【向右转】= yaw 应增大 = 需要把陀螺值反号 -> 这里的默认值是 (-1)。
 *
 *   怎么验（不用上车跑，推车就行）：
 *     1. 把车摆在发车点，车头对准赛道前进方向；
 *     2. 发 0x09 进【推车对图】模式（电机自由）；
 *     3. 沿赛道【正常往前推】一段，看遥测 YW:
 *          跟着地图中心线的方向走  -> 符号对了
 *          往反向走 / 一推就冲到 ±180 -> 把下面改成相反的符号
 *     4. 顺便核对 X:/Y: 是不是沿地图中心线走（这条验的是里程标定）。
 *
 *   符号错了会怎样：航向积分是反的，纯跟踪会朝背离赛道的一侧
 *   一路打死，上电就甩出去。所以【这一步没过不要开惯导跑】。
 * ------------------------------------------------------------ */
#define NAV_YAW_SIGN      (-1)

/* ---- 可调参数（改完重新编译；阶段 B 起改由串口 SET 下发）---- */
extern volatile int g_nav_vmax;      /* 惯导跑：直道速度（PWM） */
extern volatile int g_nav_vmin;      /* 惯导跑：最急弯的速度（PWM） */
extern volatile int g_nav_look_mm;   /* 前瞻距离(mm)：大了稳，小了跟得紧 */
extern volatile int g_nav_kgyro;     /* 陀螺阻尼增益（比纯光电模式该大一点） */
extern volatile int g_nav_corr_div;  /* 直道光电修航向的强度：越大越慢 */
extern volatile int g_nav_mm_per_e;  /* 光电 E: 1 点约等于多少 mm（现场标定） */

void     NAV_Init(void);

/* 每 5 ms 调一次（跟陀螺读取同步）：积分航向和位置 */
void     NAV_Update(int16_t w_dps);

/* 惯导跑的控制拍（由 Control_Tick 在 MODE_NAV 时调用） */
void     NAV_Run(void);

/* 开始惯导跑：把位姿复位到地图发车点（里程也清零） */
void     NAV_StartRun(void);

/* ---- 遥测 / 诊断 ---- */
int32_t  NAV_Xmm(void);           /* 当前估计位置 x，mm（场地坐标）*/
int32_t  NAV_Ymm(void);           /* 当前估计位置 y，mm */
int32_t  NAV_Yaw10(void);         /* 陀螺积出来的航向，0.1 度 */
int32_t  NAV_YawComp10(void);     /* 光电修出来的航向补偿角，0.1 度 */
int32_t  NAV_Idx(void);           /* 当前在路表上的下标 */
int32_t  NAV_LastErr(void);       /* 上一拍换算到 E: 量纲的转向误差 */
int32_t  NAV_OdoMm(void);         /* 本次跑累计里程，mm */
int32_t  NAV_LapMm(void);         /* 地图单圈长度，mm（给上层判圈用）*/
int32_t  NAV_UpdCnt(void);        /* NAV_Update 被调用次数（诊断）*/
int32_t  NAV_StraightNow(void);   /* 当前点的 kind（0/1/2，诊断）*/

#endif
